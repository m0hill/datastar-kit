import { createHash } from "node:crypto"
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises"
import path from "node:path"
import process from "node:process"

// Serves the stylesheet under a content-hashed name, so browsers can cache it forever (see
// public/_headers) instead of revalidating it, a render-blocking round trip, on every page.
// `--dev` points pages at the unhashed file that `css:watch` keeps rewriting.

const websiteRoot = path.resolve(import.meta.dirname, "..")
const publicDir = path.join(websiteRoot, "public")
const dev = process.argv.includes("--dev")

const generatedDir = path.join(websiteRoot, "src", "generated")

const writeStylesHref = async (href: string) => {
  await mkdir(generatedDir, { recursive: true })
  await writeFile(
    path.join(generatedDir, "assets.ts"),
    `// Generated by scripts/fingerprint-css.ts.\nexport const STYLES_HREF = ${JSON.stringify(href)}\n`
  )
}

if (dev) {
  await writeStylesHref("/styles.css")
} else {
  const css = await readFile(path.join(publicDir, "styles.css"))
  const name = `styles.${createHash("sha256").update(css).digest("hex").slice(0, 12)}.css`

  for (const file of await readdir(publicDir)) {
    if (/^styles\.[0-9a-f]+\.css$/.test(file) && file !== name) {
      await rm(path.join(publicDir, file))
    }
  }

  await writeFile(path.join(publicDir, name), css)
  await writeStylesHref(`/${name}`)
}
